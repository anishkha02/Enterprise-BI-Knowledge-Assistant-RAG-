def slug(s):
    return re.sub(r"[^a-z0-9]+", "_", s.lower()).strip("_")


def main():
    raw = "data/raw"
    for sub in ("kpis", "reports", "dictionary"):
        os.makedirs(f"{raw}/{sub}", exist_ok=True)
    os.makedirs("data/eval", exist_ok=True)

    kpis, domain_kpis = {}, {d: [] for d in KPI_RAW}
    for domain, block in KPI_RAW.items():
        for i, line in enumerate([l for l in block.strip().splitlines() if l.strip()]):
            name, definition, formula, tabs = line.split("|")
            tables = ", ".join(TB[t] for t in tabs.split(","))
            ssrs = SSRS[domain][i % 2][0]
            pbi = PBI[domain][i % 2][0]
            kpis[name] = dict(domain=domain, definition=definition, formula=formula,
                              tables=tables, ssrs=ssrs, pbi=pbi)
            domain_kpis[domain].append((name, i % 2, tables))

    # KPI docs
    for name, k in kpis.items():
        text = (f"# KPI: {name}\n"
                f"**Domain:** {k['domain']} | **Owner:** {k['domain']} Analytics | **Refresh:** Monthly\n"
                f"**Definition:** {k['definition']}\n"
                f"**Formula:** {k['formula']}\n"
                f"**Source Tables:** {k['tables']}\n"
                f"**Used In Reports:** {k['pbi']} (Power BI), {k['ssrs']} (SSRS)\n"
                f"**Notes:** {name} is part of the {k['domain']} KPI catalog.\n")
        open(f"{raw}/kpis/{slug(name)}.md", "w", encoding="utf-8").write(text)

    # SSRS + Power BI docs
    for domain in KPI_RAW:
        for idx, (rname, params, sched) in enumerate(SSRS[domain]):
            names = [n for n, j, _ in domain_kpis[domain] if j == idx]
            tabs = sorted({t.strip() for n, j, ts in domain_kpis[domain] if j == idx for t in ts.split(",")})
            text = (f"# SSRS Report: {rname}\n"
                    f"**Domain:** {domain}\n"
                    f"**Purpose:** Paginated {domain} report for operational review.\n"
                    f"**Parameters:** {params}\n"
                    f"**Datasets:** {', '.join(tabs)}\n"
                    f"**Refresh Schedule:** {sched}\n"
                    f"**KPIs Included:** {', '.join(names)}\n")
            open(f"{raw}/reports/ssrs_{slug(rname)}.md", "w", encoding="utf-8").write(text)
        for idx, (rname, pages, mname, dax, refresh) in enumerate(PBI[domain]):
            names = [n for n, j, _ in domain_kpis[domain] if j == idx]
            text = (f"# Power BI Dashboard: {rname}\n"
                    f"**Domain:** {domain}\n"
                    f"**Pages:** {pages}\n"
                    f"**Key Measure:** {mname}\n"
                    f"**DAX:** {dax}\n"
                    f"**Filters:** Date range slicer, Region slicer\n"
                    f"**Scheduled Refresh:** {refresh}\n"
                    f"**KPIs Included:** {', '.join(names)}\n")
            open(f"{raw}/reports/powerbi_{slug(rname)}.md", "w", encoding="utf-8").write(text)

    # Data dictionary
    for t, (desc, cols) in TABLES.items():
        kind = "Fact" if t.startswith("fact") else "Dimension"
        lines = [f"- {c.split(':')[0]} ({c.split(':')[1]}): {c.split(':')[2]}" for c in cols.split(";")]
        text = f"# Table: {t}\n**Type:** {kind} | **Description:** {desc}\n## Columns\n" + "\n".join(lines) + "\n"
        open(f"{raw}/dictionary/table_{t}.md", "w", encoding="utf-8").write(text)

    # Evaluation questions
    ssrs_flat = {r[0]: r for d in SSRS.values() for r in d}
    pbi_flat = {r[0]: r for d in PBI.values() for r in d}
    out = []
    for q, kind, key, field in QUESTIONS:
        expected, refs = [], []
        for k in key.split("|"):
            if kind == "kpi":
                kp = kpis[k]
                expected.append(f"{slug(k)}.md")
                if field == "definition": refs.append(f"{k}: {kp['definition']}")
                elif field == "formula": refs.append(f"{k} = {kp['formula']}")
                elif field == "tables": refs.append(f"{k} uses the tables: {kp['tables']}")
                elif field == "reports":
                    refs.append(f"{k} is used in {kp['pbi']} (Power BI) and {kp['ssrs']} (SSRS)")
                    expected += [f"powerbi_{slug(kp['pbi'])}.md", f"ssrs_{slug(kp['ssrs'])}.md"]
            elif kind == "ssrs":
                r = ssrs_flat[k]; expected.append(f"ssrs_{slug(k)}.md")
                refs.append(f"{k} parameters: {r[1]}" if field == "params" else f"{k} runs: {r[2]}")
            elif kind == "pbi":
                r = pbi_flat[k]; expected.append(f"powerbi_{slug(k)}.md")
                refs.append(f"{k} pages: {r[1]}" if field == "pages" else f"{k} measure: {r[3]}")
            elif kind == "table":
                desc, cols = TABLES[k]; expected.append(f"table_{k}.md")
                refs.append(f"{k}: {desc} Columns: " + "; ".join(c.split(":")[0] + " - " + c.split(":")[2] for c in cols.split(";")))
        out.append({"question": q, "expected_sources": expected, "reference": " | ".join(refs)})
    assert len(out) == 50, len(out)
    json.dump(out, open("data/eval/questions.json", "w", encoding="utf-8"), indent=2, ensure_ascii=False)

    n_docs = len(kpis) + 10 + 10 + len(TABLES)
    print(f"KPIs: {len(kpis)} | SSRS: 10 | Power BI: 10 | Tables: {len(TABLES)} | Total docs: {n_docs}")
    print(f"Eval questions: {len(out)}")


if __name__ == "__main__":
    main()